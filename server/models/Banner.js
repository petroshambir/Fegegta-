import mongoose from 'mongoose'

// ============================================================
// BANNER SCHEMA
// ============================================================

const bannerSchema = new mongoose.Schema(
  {
    // ----------------------------------------------------------
    // TITLE
    // ----------------------------------------------------------

    title: {
      type: String,
      default: '',
      trim: true,
    },

    // ----------------------------------------------------------
    // SUBTITLE
    // ----------------------------------------------------------

    subtitle: {
      type: String,
      default: '',
      trim: true,
    },

    // ----------------------------------------------------------
    // DESCRIPTION
    // ----------------------------------------------------------

    description: {
      type: String,
      default: '',
      trim: true,
    },

    // ----------------------------------------------------------
    // BUTTON TEXT
    // ----------------------------------------------------------

    buttonText: {
      type: String,
      default: '',
      trim: true,
    },

    // ----------------------------------------------------------
    // BUTTON LINK
    // ----------------------------------------------------------

    buttonLink: {
      type: String,
      default: '',
      trim: true,
    },

    // ----------------------------------------------------------
    // BANNER IMAGE
    // ----------------------------------------------------------

    image: {
      type: String,
      default: '',
      trim: true,
    },

    // ----------------------------------------------------------
    // BANNER TYPE
    // ----------------------------------------------------------

    type: {
      type: String,
      enum: [
        'image-text',
        'image-only',
        'text-only',
      ],
      default: 'image-text',
    },

    // ----------------------------------------------------------
    // ACTIVE / INACTIVE
    // ----------------------------------------------------------

    isActive: {
      type: Boolean,
      default: true,
    },

    // ----------------------------------------------------------
    // DISPLAY ORDER
    // ----------------------------------------------------------

    order: {
      type: Number,
      default: 0,
    },
  },
  {
    timestamps: true,
  }
)

// ============================================================
// INDEX
// ============================================================

bannerSchema.index({
  isActive: 1,
  order: 1,
})

// ============================================================
// MODEL
// ============================================================

const Banner = mongoose.model(
  'Banner',
  bannerSchema
)

export default Banner